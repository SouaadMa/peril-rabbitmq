export type Point = [number, number];

export type Continent = {
  label: Point;
  rings: Point[][];
};

const SCALE = 800 / 360;

export function project([lon, lat]: Point): Point {
  return [(lon + 180) * SCALE, (90 - lat) * SCALE + 30];
}

export function toPath(rings: Point[][]): string {
  return rings
    .map((ring) => {
      const points = ring.map((point) => project(point).join(" "));
      return `M ${points.join(" L ")} Z`;
    })
    .join(" ");
}

